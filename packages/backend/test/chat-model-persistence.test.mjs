import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomBytes} from 'node:crypto';
const originalCwd=process.cwd(),dir=mkdtempSync(join(tmpdir(),'dpro-model-test-'));
mkdirSync(join(dir,'.data'),{recursive:true});process.chdir(dir);
process.env.DATABASE_PATH=join(dir,'.data','agent-player.db');
process.env.AGENT_PLAYER_CONFIG_DIR=join(dir,'config');
process.env.JWT_SECRET=randomBytes(64).toString('hex');process.env.ENCRYPTION_KEY=randomBytes(32).toString('hex');
const log=console.log,info=console.info;console.log=()=>{};console.info=()=>{};
const {getDatabase,closeDatabase}=await import('../src/db/database.ts');
await getDatabase().initialize();
console.log=log;console.info=info;
const repo=await import('../src/repositories/chat-conversations.ts');
for(const id of ['fictional-a','fictional-b'])getDatabase().prepare("INSERT INTO users (id,email,username,password_hash,role,status,email_verified) VALUES (?,?,?,'fictional-hash','owner','active',1)").run(id,id+'@example.invalid',id);
test('existing model column persists independently and ownership prevents writes to another account',async()=>{
 const first=await repo.createConversation('fictional-a',{model:'subscription:codex'}),second=await repo.createConversation('fictional-a',{});
 assert.equal((await repo.findConversation('fictional-a',first.id)).model,'subscription:codex');assert.equal(second.model,undefined);
 await repo.patchConversation('fictional-b',first.id,{model:'other'});assert.equal(await repo.findConversation('fictional-b',first.id),undefined);
 assert.equal((await repo.findConversation('fictional-a',first.id)).model,'subscription:codex');
 await repo.patchConversation('fictional-a',second.id,{model:'qwen'});
 assert.equal((await repo.findConversation('fictional-a',first.id)).model,'subscription:codex');
 assert.equal((await repo.findConversation('fictional-a',second.id)).model,'qwen');
 await repo.patchConversation('fictional-a',first.id,{model:''});assert.equal((await repo.findConversation('fictional-a',first.id)).model,undefined);
 assert.equal((await repo.findConversation('fictional-a',second.id)).model,'qwen');
});
test.after(()=>{closeDatabase();process.chdir(originalCwd);rmSync(dir,{recursive:true,force:true});});
